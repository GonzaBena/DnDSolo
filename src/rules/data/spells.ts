/** Spells of one class list at one level, in the SRD's Spanish alphabetical order. */
export function spellsFor(list: string, level: number): SpellData[] {
  return SPELLS.filter((sp) => sp.level === level && sp.lists.includes(list));
}

export function findSpell(id: string): SpellData | undefined {
  return SPELLS.find((sp) => sp.id === id);
}

/** Pick options for the spells of one class list at one level (option id = spell id). */
export function spellOptions(list: string, level: number): Option[] {
  return spellsFor(list, level).map((sp) => ({ id: sp.id, name: sp.name, summary: sp.summary }));
}
