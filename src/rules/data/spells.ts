/** Spells of SRD 5.2.1 from cantrips to level 5 (enough for characters up to level 10). Names, schools and class
    lists follow the official Spanish SRD; ids are English snake_case. Data only. */
export interface SpellData {
  id: string;
  name: string;
  level: 0 | 1 | 2 | 3 | 4 | 5;
  school: string;
  /** Class ids whose spell list includes this spell. */
  lists: string[];
  summary: string;
  source: "SRD 5.2";
  /** Has the Ritual tag ("R" in the SRD spell list tables). */
  ritual: boolean;
  /** Cantrips that deal damage on their own: whether via an attack roll, and their range in feet
      (0 for Touch or Self). Used by warlock invocations such as Agonizing Blast. */
  damage?: { attackRoll: boolean; rangeFt: number };
}

